const makeUnit = (
  id: string,
  name: string,
  stats: Stats,
  weaponId: string,
  renderClassId: string,
  skillId: string | null,
  faction: Unit['faction'],
): Unit => ({
  id,
  name,
  faction,
  stats,
  hp: stats.hp,
  weaponId,
  artWeaponId: WEAPONS[weaponId].artWeaponId,
  renderClassId,
  classId: faction === 'player' ? 'infantry' : 'yellow_raider',
  className: faction === 'player' ? '义军步兵' : id === 'yellow_chief' ? '黄巾头目' : '黄巾剑兵',
  portraitId: faction === 'player' ? `${id}_early_calm` : 'yellow_chief_standard_calm',
  avatarId: faction === 'player' ? `${id}_early_avatar` : 'yellow_chief_standard_avatar',
  x: 0,
  y: 0,
  level: faction === 'player' ? 1 : id === 'yellow_chief' ? 3 : 1,
  exp: 0,
  acted: false,
  alive: true,
  potions: faction === 'player' ? 3 : 0,
  skillId,
  facing: faction === 'player' ? 1 : -1,
  sp: 0,
  burst: 0,
  statuses: [],
});

